import { JSON } from "..";


@json
class NumericDefaults {
  maximum: u32 = U32.MAX_VALUE;
  floating: f64 = F64.MAX_VALUE;
  items: i32[] = [1, 2, 3];
}


@json
class Nested {
  rows: NumericDefaults[] = [];
}
namespace Shadow {
  let calls: i32 = 0;
  class U32 {
    static get MAX_VALUE(): i32 {
      return ++calls;
    }
  }


  @json
  class Row {

    @optional maximum: i32 = U32.MAX_VALUE;
  }
  export function verify(): string {
    calls = 0;
    const row = JSON.parse<Row>("{}");
    // @ts-ignore: generated by transform
    return (
      isDefined(row.__DESERIALIZE_FAST).toString() +
      ":" +
      row.maximum.toString() +
      ":" +
      calls.toString()
    );
  }
}
export function verify(): string {
  const row = new NumericDefaults();
  const nested = new Nested();
  const input = '{"rows":[{"maximum":7,"floating":1.5,"items":[4,5,6]}]}';
  const result = JSON.parse<Nested>(input);
  if (JSON.stringify(result) != input) unreachable();
  JSON.parse<Nested>(input, result);
  if (JSON.stringify(result) != input) unreachable();
  // @ts-ignore: generated by transform
  return (
    isDefined(row.__DESERIALIZE_FAST).toString() +
    "|" +
    // @ts-ignore: generated by transform
    isDefined(nested.__DESERIALIZE_FAST).toString() +
    "|" +
    Shadow.verify()
  );
}
