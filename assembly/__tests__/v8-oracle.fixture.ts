export function allocInput(bytes: i32): usize {
  return __new(bytes, idof<string>());
}
export function run(kind: i32, source: string): string {
  if (kind == 0) return JSON.stringify(JSON.parse<JSON.Value>(source));
  if (kind == 1) return JSON.stringify(JSON.parse<Parent>(source));
  if (kind == 2) {
    pair.b = pair.a;
    return JSON.stringify(JSON.parse<Pair>(source, pair));
  }
  if (kind == 3) {
    const row: i32[] = [0];
    matrix.rows = [row, row];
    const floats: f64[] = [0];
    matrix.floats = [floats, floats];
    const plane: i32[][] = [[0]];
    matrix.planes = [plane, plane];
    return JSON.stringify(JSON.parse<Matrix>(source, matrix));
  }
  if (kind == 4) return JSON.stringify(JSON.parse<Model.Record>(source));
  if (kind == 5) return JSON.stringify(JSON.parse<PrefixHolder>(source));
  if (kind == 6) return JSON.stringify(JSON.parse<f64>(source));
  if (kind == 7) return JSON.stringify(JSON.parse<Date>(source));
  if (kind == 8) return JSON.stringify(JSON.parse<Date[]>(source));
  if (kind == 9) return JSON.stringify(JSON.parse<DateHolder>(source));
  return JSON.stringify(JSON.parse<Wide>(source));
}
export function fastWide(source: string): bool {
  const value = new Wide();
  // @ts-ignore: generated by transform, unavailable when fast paths disabled
  if (isDefined(value.__DESERIALIZE_FAST))
    return (
      value.__DESERIALIZE_FAST<Wide>(
        changetype<usize>(source),
        changetype<usize>(source) + ((<usize>source.length) << 1),
        value,
      ) != 0
    );
  return false;
}

let callbackKind: i32 = 0;
let callbackObject = new JSON.Obj();
let callbackArray = new JSON.Arr();


@json class Mutator {

  @serializer serialize(): string {
    if (callbackKind == 0) callbackObject.delete("b");
    else if (callbackKind == 3) {
      callbackArray.length = 1;
      return "7";
    } else if (callbackKind == 4) callbackArray.length = 0;
    else {
      for (let i = 0; i < (callbackKind == 1 ? 1 : 7); i++)
        callbackArray.push<i32>(3);
      callbackArray.set<i32>(1, 9);
    }
    return "1";
  }
}
export function mutation(kind: i32): string {
  callbackKind = kind;
  if (kind == 0) {
    callbackObject = new JSON.Obj();
    callbackObject.set("a", new Mutator());
    callbackObject.set<i32>("b", 2);
    callbackObject.set<i32>("c", 3);
    return JSON.stringify(callbackObject);
  }
  callbackArray = new JSON.Arr();
  callbackArray.push(new Mutator());
  callbackArray.push<i32>(2);
  callbackArray.push<i32>(3);
  return kind == 3 ? callbackArray.join(",") : JSON.stringify(callbackArray);
}


