import fs from "node:fs";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
const source = fs.readFileSync(
  new URL("node_modules/xjb-as/assembly/xjb.ts", root),
  "utf8",
);
assert.equal(
  createHash("sha256").update(source).digest("hex"),
  "53e55e3d9703a4fb4107bec1ac0b189d4356440213e37029eb1b1d45bc0c68a7",
);
const mask = (1n << 64n) - 1n;
function power(index) {
  assert.ok(Number.isInteger(index) && index >= 0 && index < 618);
  const exponent = index - 293;
  const exact = 10n ** BigInt(Math.abs(exponent));
  const bits = exact.toString(2).length;
  const normalized =
    exponent >= 0
      ? bits <= 128
        ? exact << BigInt(128 - bits)
        : exact >> BigInt(bits - 128)
      : (1n << BigInt(127 + bits)) / exact;
  return { hi: normalized >> 64n, lo: normalized & mask };
}
function frame(rawExp) {
  const q = rawExp - 1075,
    decExp = (q * 78913) >> 18,
    powExp = -decExp - 1,
    h = q + ((powExp * 217707) >> 16),
    shift = h + 7,
    p = power(powExp + 293);
  return { hi: p.hi, lo: (p.lo + BigInt(powExp < 0)) & mask, decExp, h, shift };
}
const cells = Array.from({ length: 2048 }, (_, raw) => {
  const f = frame(raw);
  return [
    f.hi,
    f.lo,
    BigInt.asUintN(32, BigInt(f.decExp)) |
      (BigInt.asUintN(32, BigInt(f.shift)) << 32n),
    BigInt.asUintN(32, BigInt(f.h)),
  ];
}).flat();
assert.equal(cells.length, 8192);

const bytes = Buffer.alloc(cells.length * 8);
cells.forEach((value, index) => bytes.writeBigUInt64LE(value, index * 8));
const output = new URL("transform/src/array-exponent-data.ts", root);
const header = fs
  .readFileSync(new URL("transform/src/array-dtoa.ts", root), "utf8")
  .split("import ", 1)[0];
const text =
  header +
  '// Generated by scripts/update-array-exponent-data.mjs from xjb-as; see NOTICE.\n\nexport const STOCK_POWER_SOURCE =\n  "53e55e3d9703a4fb4107bec1ac0b189d4356440213e37029eb1b1d45bc0c68a7";\n\nexport const ARRAY_EXPONENT_DATA: string =\n  "' +
  bytes.toString("base64") +
  '";\n';
if (process.argv.includes("--check"))
  assert.equal(
    fs.readFileSync(output, "utf8"),
    text,
    "Regenerate array exponent metadata",
  );
else fs.writeFileSync(output, text);
console.log(
  "Array exponent data:",
  bytes.length,
  "bytes;2048 rows;known xjb source",
);
